import lombok.Generated;

public class Waypoint {
    private double x;
    private double z;

    @Generated
    public Waypoint(double x2, double z2) {
        this.x = x2;
        this.z = z2;
    }

    @Generated
    public double getX() {
        return this.x;
    }

    @Generated
    public double getZ() {
        return this.z;
    }
}