    private static final long RAINBOW_TRANSITION_MS = 300L;

    private static boolean rainbowEnabled = false;
    private static double rainbowSpeed = 1.0;
    private static float rainbowBlend = 0.0f;
    private static float rainbowBlendFrom = 0.0f;
    private static float rainbowBlendTarget = 0.0f;
    private static long rainbowBlendStart = System.currentTimeMillis();

    public static void setRainbow(boolean enabled, double speed) {
        rainbowSpeed = speed;
        updateRainbowBlend();

        if (rainbowEnabled == enabled) {
            return;
        }

        rainbowEnabled = enabled;
        rainbowBlendFrom = rainbowBlend;
        rainbowBlendTarget = enabled ? 1.0f : 0.0f;
        rainbowBlendStart = System.currentTimeMillis();
    }

    public static boolean isRainbowEnabled() {
        updateRainbowBlend();
        return rainbowEnabled || rainbowBlend > 0.001f;
    }
    public static double getRainbowSpeed() { return rainbowSpeed; }

    public static int getAccentColor(float alpha) {
        return blendAbgr(getThemeAccentColor(alpha), getRawRainbow(alpha), getRainbowBlend());
    }

    public static int getAccentHoverColor(float alpha) {
        return blendAbgr(getThemeAccentHoverColor(alpha), getRawRainbow(alpha), getRainbowBlend());
    }

    public static int getRainbow(float alpha) {
        return getAccentColor(alpha);
    }

    private static float getRainbowBlend() {
        updateRainbowBlend();
        return rainbowBlend;
    }

    private static void updateRainbowBlend() {
        long elapsed = System.currentTimeMillis() - rainbowBlendStart;
        if (elapsed >= RAINBOW_TRANSITION_MS) {
            rainbowBlend = rainbowBlendTarget;
            return;
        }

        float t = Math.max(0.0f, elapsed / (float) RAINBOW_TRANSITION_MS);
        t = t * t * (3.0f - 2.0f * t);
        rainbowBlend = rainbowBlendFrom + (rainbowBlendTarget - rainbowBlendFrom) * t;
    }

